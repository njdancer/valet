// Turns the token objects into CSS. scripts/build-tokens.ts writes the result to
// src/styles/tokens.css and src/styles/theme.css; a test checks those files are current.

import {
  black,
  breakpoints,
  duration,
  easing,
  font,
  fontSize,
  fontWeight,
  letterSpacing,
  lineHeight,
  palette,
  radius,
  space,
  white,
  zIndex,
} from './primitives'
import { type ColorRef, color, material, shadow, type Themed } from './semantic'

/** The CSS for one colour reference: a primitive's variable, mixed with transparent for alpha. */
export function refToCss(ref: ColorRef): string {
  if (/^(oklch\(|linear-gradient|blur\()/.test(ref) || ref === 'none') return ref
  const [name, alpha] = ref.split('/') as [string, string | undefined]
  const base =
    name === 'white' || name === 'black' ? `var(--v-${name})` : `var(--v-${name.replace('.', '-')})`
  if (alpha === undefined) return base
  return `color-mix(in oklab, ${base} ${alpha}%, transparent)`
}

/** The literal colour (an oklch() string) and alpha a reference stands for, for the contrast test. */
export function resolveRef(ref: ColorRef): { readonly color: string; readonly alpha: number } {
  const [name, alpha] = ref.split('/') as [string, string | undefined]
  const a = alpha === undefined ? 1 : Number(alpha) / 100
  if (name === 'white') return { color: white, alpha: a }
  if (name === 'black') return { color: black, alpha: a }
  const [scaleName, step] = name.split('.') as [keyof typeof palette, string]
  const scale = palette[scaleName]
  const value = scale?.[step]
  if (value === undefined) throw new Error(`Unknown colour reference ${ref}`)
  return { color: value, alpha: a }
}

const block = (selector: string, lines: readonly string[]) =>
  `${selector} {\n${lines.map((l) => `  ${l}`).join('\n')}\n}\n`

function themed(theme: 'light' | 'dark'): string[] {
  const lines: string[] = [`color-scheme: ${theme};`]
  for (const [name, value] of Object.entries(color) as [string, Themed][]) {
    lines.push(`--${name}: ${refToCss(value[theme])};`)
  }
  for (const [name, value] of Object.entries(shadow) as [string, Themed][]) {
    lines.push(`--elevation-${name}: ${value[theme]};`)
  }
  for (const [name, value] of Object.entries(material) as [string, Themed][]) {
    lines.push(`--material-${name}: ${refToCss(value[theme])};`)
  }
  return lines
}

export function tokensCss(): string {
  const prim: string[] = []
  prim.push(`--v-white: ${white};`, `--v-black: ${black};`)
  for (const [scaleName, scale] of Object.entries(palette)) {
    for (const [step, value] of Object.entries(scale)) prim.push(`--v-${scaleName}-${step}: ${value};`)
  }
  prim.push(`--v-font-sans: ${font.sans};`, `--v-font-mono: ${font.mono};`)
  for (const [k, v] of Object.entries(fontSize)) prim.push(`--v-font-size-${k}: ${v}px;`)
  for (const [k, v] of Object.entries(lineHeight)) prim.push(`--v-leading-${k}: ${v};`)
  for (const [k, v] of Object.entries(fontWeight)) prim.push(`--v-weight-${k}: ${v};`)
  for (const [k, v] of Object.entries(letterSpacing)) prim.push(`--v-tracking-${k}: ${v};`)
  for (const [k, v] of Object.entries(space)) prim.push(`--v-space-${String(k).replace('.', '_')}: ${v}px;`)
  for (const [k, v] of Object.entries(radius)) prim.push(`--v-radius-${k}: ${v}px;`)
  for (const [k, v] of Object.entries(duration)) prim.push(`--v-duration-${k}: ${v}ms;`)
  for (const [k, v] of Object.entries(easing)) prim.push(`--v-ease-${k}: ${v};`)
  for (const [k, v] of Object.entries(zIndex)) prim.push(`--v-z-${k}: ${v};`)
  for (const [k, v] of Object.entries(breakpoints)) prim.push(`--v-breakpoint-${k}: ${v}px;`)
  // How far things travel when they enter. Reduced motion sets it to 0, so entrances only fade.
  prim.push('--v-motion-distance: 1;')

  const light = themed('light')
  const dark = themed('dark')
  return [
    '/* Generated by packages/ui/scripts/build-tokens.ts from src/tokens. Do not edit by hand. */\n',
    block(':root', prim),
    block(':root,\n[data-theme="light"]', light),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', dark)
      .split('\n')
      .map((l) => (l ? `  ${l}` : l))
      .join('\n')}}\n`,
    block('[data-theme="dark"]', dark),
    `@media (prefers-reduced-motion: reduce) {\n  :root {\n    --v-motion-distance: 0;\n  }\n}\n`,
  ].join('\n')
}

/** Tailwind's name for a semantic colour: bg-surface, text-fg-muted, border-line-strong. */
export function tailwindName(token: string): string {
  if (token.startsWith('bg-')) return token.slice(3)
  if (token === 'fg-default') return 'fg'
  if (token === 'border-default') return 'line'
  if (token.startsWith('border-')) return `line-${token.slice(7)}`
  return token
}

export function themeCss(): string {
  const lines: string[] = []
  // Clear Tailwind's own palette so only Valet's tokens exist as colour utilities.
  lines.push('--color-*: initial;', '--color-transparent: transparent;', '--color-current: currentColor;')
  lines.push('--color-white: var(--v-white);', '--color-black: var(--v-black);')
  for (const name of Object.keys(color)) lines.push(`--color-${tailwindName(name)}: var(--${name});`)
  lines.push('--font-*: initial;', '--font-sans: var(--v-font-sans);', '--font-mono: var(--v-font-mono);')
  lines.push('--text-*: initial;')
  const leadingFor: Record<string, keyof typeof lineHeight> = {
    '2xs': 'snug',
    xs: 'snug',
    sm: 'normal',
    md: 'normal',
    lg: 'snug',
    xl: 'snug',
    '2xl': 'tight',
    '3xl': 'tight',
    '4xl': 'tight',
  }
  for (const k of Object.keys(fontSize)) {
    lines.push(`--text-${k}: var(--v-font-size-${k});`)
    lines.push(`--text-${k}--line-height: var(--v-leading-${leadingFor[k] ?? 'normal'});`)
  }
  lines.push('--font-weight-*: initial;')
  for (const k of Object.keys(fontWeight)) lines.push(`--font-weight-${k}: var(--v-weight-${k});`)
  lines.push('--tracking-*: initial;')
  for (const k of Object.keys(letterSpacing)) lines.push(`--tracking-${k}: var(--v-tracking-${k});`)
  lines.push('--spacing: 4px;')
  lines.push('--radius-*: initial;')
  for (const k of Object.keys(radius)) lines.push(`--radius-${k}: var(--v-radius-${k});`)
  lines.push('--shadow-*: initial;')
  for (const k of Object.keys(shadow)) lines.push(`--shadow-${k}: var(--elevation-${k});`)
  lines.push('--ease-*: initial;')
  for (const k of Object.keys(easing)) lines.push(`--ease-${k}: var(--v-ease-${k});`)
  lines.push('--breakpoint-*: initial;')
  for (const [k, v] of Object.entries(breakpoints)) lines.push(`--breakpoint-${k}: ${v}px;`)
  return [
    '/* Generated by packages/ui/scripts/build-tokens.ts from src/tokens. Do not edit by hand. */\n',
    block('@theme inline', lines),
  ].join('\n')
}
