// Copies Playwright's in-page script (its "injected script": the accessibility snapshot, aria refs
// and selector engines) out of the pinned playwright-core into src/generated/, so the agents'
// browser reads pages the way Playwright MCP does without shipping Playwright or opening a
// debugging port. Run after bumping playwright-core:
//   node packages/browser-electron/scripts/vendor-playwright.mjs
// test/playwright-vendor.test.ts fails while the copy and the installed version differ.

import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '..', 'src', 'generated', 'playwright-injected.ts')

/** The injected script's source and the version it came from. */
export function extractInjectedScript() {
  const require = createRequire(join(here, '..', 'package.json'))
  const pkgPath = require.resolve('playwright-core/package.json')
  const { version } = JSON.parse(readFileSync(pkgPath, 'utf8'))
  const bundle = readFileSync(join(dirname(pkgPath), 'lib', 'coreBundle.js'), 'utf8')
  const marker = '"packages/playwright-core/src/generated/injectedScriptSource.ts"() {'
  const at = bundle.indexOf(marker)
  if (at < 0) throw new Error('playwright-core no longer bundles injectedScriptSource.ts where expected')
  // The module body is `"use strict";\n    <name> = '<source>';` : take that one string literal.
  const assign = /\n\s+[A-Za-z_$][\w$]* = '/g
  assign.lastIndex = at
  const found = assign.exec(bundle)
  if (found === null) throw new Error('injected script literal not found')
  const start = found.index + found[0].length - 1
  let end = start + 1
  while (end < bundle.length) {
    const ch = bundle[end]
    if (ch === '\\') end += 2
    else if (ch === "'") break
    else end++
  }
  // A plain single-quoted JS string literal: JSON can't read it, so evaluate just that literal.
  const source = new Function(`return ${bundle.slice(start, end + 1)}`)()
  if (typeof source !== 'string' || !source.includes('InjectedScript'))
    throw new Error('injected script looks wrong')
  const patched = applyPatches(source)
  return { version, source: patched, sha256: createHash('sha256').update(patched).digest('hex') }
}

/**
 * Valet's two hooks into the snapshot, so it shows what a person can see on the page and nothing a
 * page hides for an agent (src/aria.ts defines them in the runtime's isolated world):
 * __valetHidden(element) skips an element and everything in it; __valetName(element, name) names a
 * node by its visible words rather than an aria-label, title or alt no one sees. Each patch must
 * apply exactly once, so a Playwright upgrade that moves the code fails here, not quietly.
 */
export const PATCHES = [
  {
    find: '    const element = node;\n    const isElementVisibleForAria = !isElementHiddenForAria(element);\n',
    replace:
      '    const element = node;\n' +
      '    if (typeof globalThis.__valetHidden === "function" && globalThis.__valetHidden(element))\n' +
      '      return;\n' +
      '    const isElementVisibleForAria = !isElementHiddenForAria(element);\n',
  },
  {
    find: '    name: normalizeWhiteSpace(name.text),\n',
    replace:
      '    name: normalizeWhiteSpace(typeof globalThis.__valetName === "function" ? globalThis.__valetName(element, name.text) : name.text),\n',
  },
]

function applyPatches(source) {
  let out = source
  for (const patch of PATCHES) {
    const count = out.split(patch.find).length - 1
    if (count !== 1) throw new Error(`patch anchor found ${count} times: ${patch.find.slice(0, 60)}`)
    out = out.replace(patch.find, patch.replace)
  }
  return out
}

export function render({ version, source, sha256 }) {
  return (
    '// Generated by scripts/vendor-playwright.mjs from playwright-core ' +
    `${version}. Do not edit.\n` +
    '// Playwright, Copyright (c) Microsoft Corporation, Apache License 2.0 (see NOTICE).\n\n' +
    `export const PLAYWRIGHT_VERSION = '${version}'\n` +
    `export const INJECTED_SHA256 = '${sha256}'\n` +
    `export const INJECTED_SOURCE: string = ${JSON.stringify(source)}\n`
  )
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const extracted = extractInjectedScript()
  writeFileSync(out, render(extracted))
  console.log(`playwright-core ${extracted.version}: ${extracted.source.length} chars -> ${out}`)
}
